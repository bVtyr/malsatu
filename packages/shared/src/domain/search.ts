const INDEX = new Map<string, Set<string>>();
for (const group of SYNONYMS) {
  const set = new Set(group.map((w) => w.toLowerCase()));
  for (const w of set) INDEX.set(w, set);
}

/** Казахские буквы → ближайшие кириллические (для «ленивого» ввода и опечаток). */
export function foldKazakh(s: string): string {
  return s
    .toLowerCase()
    .replace(/ә/g, "а").replace(/ғ/g, "г").replace(/қ/g, "к").replace(/ң/g, "н")
    .replace(/ө/g, "о").replace(/ұ/g, "у").replace(/ү/g, "у").replace(/һ/g, "х").replace(/і/g, "и")
    .replace(/ё/g, "е");
}

/** Раскрывает запрос в набор терминов: исходные слова + синонимы (обе языковые формы). */
export function expandQuery(q: string): string[] {
  const words = q.toLowerCase().split(/[\s,]+/).filter(Boolean);
  const out = new Set<string>();
  // сначала проверяем составные фразы (2 слова)
  for (let i = 0; i < words.length; i++) {
    const w = words[i]!;
    const two = i + 1 < words.length ? `${w} ${words[i + 1]}` : null;
    if (two && INDEX.has(two)) { for (const s of INDEX.get(two)!) out.add(s); i++; continue; }
    out.add(w);
    const syn = INDEX.get(w) ?? INDEX.get(foldKazakh(w));
    if (syn) for (const s of syn) out.add(s);
  }
  return [...out];
}

/** Строит tsquery-строку для PostgreSQL ('simple' конфигурация + префиксный поиск). */
export function toTsQuery(q: string): string {
  const terms = expandQuery(q).map((t) => t.replace(/[^\p{L}\p{N} ]/gu, "").trim()).filter(Boolean);
  if (terms.length === 0) return "";
  // префиксный поиск только для слов от 4 букв: «ат:*» иначе ловит «атбасар», «каз:*» — «казы» и «казахская»
  return terms.map((t) => t.split(" ").map((w) => (w.length >= 4 ? `${w}:*` : w)).join(" & ")).map((t) => `(${t})`).join(" | ");
}
